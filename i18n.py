def _translate_portuguese(source):
    value = str(source)
    exact = _PT_EXACT.get(value)
    if exact is not None:
        return exact
    translated = value
    for english, portuguese in _PT_REPLACEMENTS:
        translated = translated.replace(english, portuguese)
    return translated


def translate(source):
    """Translate a Processing/UI source string using the active language."""
    value = str(source)
    current = language()
    if current == "es":
        return _ES.get(value, value)
    if current == "pt":
        return _translate_portuguese(value)
    return value
